#!/bin/bash

# смотрим какие процессы больше всего ресурсов используют
# когда система тормозит надо понять что происходит  
# версия 1.0

echo "=== мониторинг процессов ==="
echo $(date)
echo ""

# общая нагрузка системы
echo "текущая нагрузка:"
uptime | awk -F'load average:' '{print $2}'
echo ""

# топ процессов по CPU
echo "больше всего CPU используют:"
ps aux --sort=-%cpu | head -6 | awk '{printf "%-10s %5s%% %s\n", $1, $3, $11}'
echo ""

# топ процессов по памяти  
echo "больше всего памяти используют:"
ps aux --sort=-%mem | head -6 | awk '{printf "%-10s %5s%% %s\n", $1, $4, $11}'
echo ""

# количество процессов по пользователям
echo "процессов по пользователям:"
ps aux | awk '{print $1}' | sort | uniq -c | sort -nr | head -5
echo ""

# TODO: добавить проверку zombie процессов

# ищем процессы которые долго работают
echo "процессы работающие дольше суток:"
ps -eo pid,etime,comm | awk '$2 ~ /-/ {print $1, $2, $3}' | head -3

echo ""

# общая статистика
TOTAL_PROC=$(ps aux | wc -l)
echo "всего процессов:" $TOTAL_PROC
echo "активных пользователей:" $(users | wc -w)

echo ""
echo "мониторинг завершён"
