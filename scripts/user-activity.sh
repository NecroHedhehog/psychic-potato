#!/bin/bash

# смотрим кто и когда заходил в систему
# полезно для контроля доступа к серверу
# версия 1.0

echo "=== активность пользователей ==="
echo $(date)
echo ""

# кто сейчас в системе
echo "текущие пользователи:"
who
echo ""

# последние входы в систему
echo "последние 10 входов:"
last -n 10 | head -10
echo ""

# неудачные попытки входа
echo "неудачные попытки входа:"
lastb -n 5 2>/dev/null | head -5 || echo "логи недоступны"
echo ""

# TODO: добавить анализ sudo активности

# пользователи с правами sudo
echo "пользователи с sudo правами:"
grep -E '^sudo:' /etc/group | cut -d: -f4 || echo "группа sudo не найдена"
echo ""

# все пользователи в системе
echo "всего пользователей в системе:"
cat /etc/passwd | grep -E '/bin/(bash|sh)$' | wc -l
echo ""

# активность текущего пользователя  
echo "ваша последняя активность:"
last -n 3 $USER | head -3
echo ""

# проверяем блокированные аккаунты
echo "заблокированные аккаунты:"
passwd -Sa 2>/dev/null | grep ' L ' | wc -l | awk '{print $1 " аккаунтов"}'

echo ""
echo "проверка завершена"
