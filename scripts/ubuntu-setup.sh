#!/bin/bash

# скрипт для мониторинга Ubuntu сервера
# собрал из разных источников для быстрой диагностики
# V 2.0

echo "=== Диагностика системы ==="
echo "Время запуска: $(date)"
echo ""

# базовая информация о системе
echo ">> Информация о системе:"
echo "Дистрибутив: $(lsb_release -d 2>/dev/null | cut -f2 || echo "Ubuntu")"
echo "Версия ядра: $(uname -r)"
echo "Время работы: $(uptime -p)"
echo ""

# проверка свободного места - критично для работы
echo ">> Использование дисков:"
df -h | grep -E '^/dev/' | awk '{print $1 ": " $3 "/" $2 " (использовано " $5 ")"}'
echo ""

# мониторинг RAM
echo ">> Память:"
free -h | grep Mem | awk '{print "Использовано: " $3 " из " $2}'
echo ""

# нагрузка на процессор - для выявления проблем
echo ">> Загрузка CPU:"
echo "$(cat /proc/loadavg | awk '{print "1 мин: " $1 ", 5 мин: " $2 ", 15 мин: " $3}')"
echo ""

# сетевые настройки
echo ">> Сеть:"
ip addr show | grep 'inet ' | grep -v '127.0.0.1' | awk '{print "IP адрес: " $2}' | head -1
echo ""

# количество запущенных процессов
echo ">> Процессы:"
echo "Всего процессов: $(ps aux | wc -l)"
echo "Процессов пользователя: $(ps -u $USER | wc -l)"
echo ""

# проверка системных событий
echo ">> Последние события в логах:"
journalctl --no-pager -n 3 --since "1 hour ago" 2>/dev/null | tail -3 || echo "Доступ к журналам ограничен"
echo ""

# очистка временных файлов
echo ">> Очистка системы..."
if [ -w /tmp ]; then
    # удаляем старые tmp файлы старше суток
    find /tmp -type f -name "*.tmp" -mtime +1 -delete 2>/dev/null
    echo "Временные файлы очищены"
else
    echo "Недостаточно прав для очистки /tmp"
fi

echo ""
echo ">> Проверка завершена"
